"use strict";
const assert=require("node:assert/strict");
const {harness,fixture}=require("./state_consistency.test.js");
async function main() {
  const h=harness(), app=h.app;
  app.setPattern(fixture());
  app.state.boundary=[[0,0],[1,0]];
  const original=JSON.stringify(app.sessionState()), old=app.worker;
  const pending=app.request("vector");
  const rejected=assert.rejects(pending,/engine stopped/);
  old.onerror(); await rejected; await Promise.resolve();
  assert.equal(app.awaitingCount,0,"fatal failure settles and clears every request");
  assert(old.terminated); assert.equal(h.node("retry-engine").hidden,false);
  assert.equal(JSON.stringify(app.sessionState()),original,"failure preserves user state");
  await assert.rejects(app.request("count"),/engine stopped/);
  app.state.center=[100,0];
  await app.exportPNG();
  assert.equal(h.exports,0,"export outside cached coverage settles after Worker failure");
  app.state.center=[0,0];
  const retry=app.retryEngine();
  const replacement=app.worker;
  assert.notEqual(replacement,old);
  const metadata=h.last("metadata");
  old.onmessage({data:{id:metadata.id,type:"result",result:{}}});
  assert.equal(app.awaitingCount,1,"retired Worker cannot settle replacement requests");
  h.reply(metadata,{lattice:"FCC",axis:"110",layers:1,max_angle:90,presets:[],reference_labels:[],layer_spacing:1,axial_period:1});
  await retry;
  h.flush(45); h.reply(h.last("render"),fixture()); await Promise.resolve();
  assert(app.currentPattern()); assert.equal(h.node("retry-engine").hidden,true);
  assert.equal(JSON.stringify(app.sessionState()),original,"restart retains geometry and selections");
  h.sandbox.failPost=true;
  await assert.rejects(app.request("count"),/Cannot post/);
  assert.equal(app.awaitingCount,0,"postMessage exceptions settle pending requests");
  h.sandbox.failPost=false;
  const second=app.retryEngine(); app.worker.onmessageerror(); await second;
  assert.equal(h.node("retry-engine").hidden,false,"failed retries remain recoverable");
  assert.equal(app.awaitingCount,0);
  console.log("Worker fatal errors, post failures, replacement isolation, and explicit retry passed.");
}
main().catch(error=>{console.error(error);process.exitCode=1;});
